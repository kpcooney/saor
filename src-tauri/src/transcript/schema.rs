// transcript/schema.rs
//
// The shape of one session-transcript line (ADR-013). Field names are
// camelCase on disk, over the storage bridge, and over IPC, matching the audit
// event schema. Mirrored by `TranscriptEntry` in agents/src/transcript/entries.ts
// (what the sidecar sends, minus `sessionId`) and in src/lib/types.ts (what the
// UI reads).

use serde::{Deserialize, Serialize};
use serde_json::Value;

/// What a transcript entry records.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum TranscriptEntryKind {
    /// The task the agent was launched with. First entry of a run.
    Task,
    /// One turn of the agent speaking. `text` may be empty when the turn was
    /// only tool calls; `details.toolUseIds` lists those calls by id.
    Message,
    /// How the run ended: `text` is the agent's final answer, or the error.
    /// `details` carries `isError` and, when the SDK reported them,
    /// `numTurns`, `durationMs`, and `totalCostUsd`.
    Result,
}

/// One line of a session transcript.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TranscriptEntry {
    /// The Saor session the entry belongs to. Stamped by the Rust side from
    /// the session the bridge is bound to, never taken from the sidecar.
    pub session_id: String,
    /// ISO-8601 time the sidecar observed the message.
    pub timestamp: String,
    pub kind: TranscriptEntryKind,
    pub text: String,
    /// Kind-specific structured context; an empty object when there is none.
    #[serde(default)]
    pub details: Value,
}

#[derive(Debug, thiserror::Error)]
pub enum TranscriptError {
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),

    #[error("serialization error: {0}")]
    Serialization(#[from] serde_json::Error),

    #[error("failed to create transcript directory: {0}")]
    DirectoryCreation(String),

    /// The session id cannot be used as a file name. Session ids are
    /// generated by the process manager (`session-<uuid>`), so this means the
    /// id came from somewhere else.
    #[error("invalid session id \"{0}\": expected letters, digits, '-' or '_'")]
    InvalidSessionId(String),
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn test_transcript_entry_uses_camel_case_fields_and_lowercase_kinds() {
        let entry = TranscriptEntry {
            session_id: "session-1".to_string(),
            timestamp: "2026-11-24T02:39:40.000Z".to_string(),
            kind: TranscriptEntryKind::Message,
            text: "Looking at the project.".to_string(),
            details: json!({ "toolUseIds": ["tu-1"] }),
        };

        let value = serde_json::to_value(&entry).unwrap();
        assert_eq!(value["sessionId"], "session-1");
        assert_eq!(value["kind"], "message");
        assert_eq!(value["details"]["toolUseIds"][0], "tu-1");
        // Negative control: the snake_case name is not emitted.
        assert!(value.get("session_id").is_none());

        let parsed: TranscriptEntry = serde_json::from_value(value).unwrap();
        assert_eq!(parsed, entry);
    }
}
